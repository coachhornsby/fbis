export function searchCfbdRegistry(query = "") {
  const q = String(query || "").trim().toLowerCase();
  const endpoints = !q
    ? [...CFBD_ENDPOINT_REGISTRY]
    : CFBD_ENDPOINT_REGISTRY.filter((d) => {
        const hay = [
          d.id, d.endpoint, d.name, d.units, d.ingestionMechanism, d.storage,
          ...(d.fields || []), ...(d.gaps || []), ...(d.unusedByChampion || []),
        ]
          .join(" ")
          .toLowerCase();
        return hay.includes(q);
      });
  const features = !q
    ? [...CFBD_FEATURE_CATALOG]
    : CFBD_FEATURE_CATALOG.filter((f) => {
        const hay = [f.canonical, f.group, f.endpoint, f.unit, ...(f.rawFields || []), f.notes || ""]
          .join(" ")
          .toLowerCase();
        return hay.includes(q);
      });
  return { endpoints, features };
}

export function summarizeCfbdRegistry() {
  const endpoints = CFBD_ENDPOINT_REGISTRY;
  return {
    version: CFBD_REGISTRY_VERSION,
    featureCatalogVersion: FEATURE_CATALOG_VERSION,
    nEndpoints: endpoints.length,
    nFeatureCatalogRows: CFBD_FEATURE_CATALOG.length,
    collectedCurrently: endpoints.filter((d) => d.collectedCurrently).length,
    championEndpoints: endpoints.filter((d) => d.championConsumes).length,
    researchEndpoints: endpoints.filter((d) => d.researchConsumes).length,
    evaluationOnly: endpoints.filter((d) => d.evaluationOnly).length,
    sharedQuotaNote:
      "CFBD+CBBD share monthly allowance (defaults CFBD_DAILY_NETWORK_BUDGET=45, CFBD_MONTHLY_NETWORK_BUDGET=1400; stop remaining≤100)",
    championContract:
      "Fitted M*=A/T*=A consumes only blended prior+overall PPA base/base_total and observation count n",
  };
}
